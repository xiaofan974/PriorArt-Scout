import { createRequire } from 'node:module';
import Module from 'node:module';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ARTIFACT = path.join(ROOT, 'api/extract-features.js');
const BUILD_SCRIPT = path.join(ROOT, 'scripts/build-api.mjs');

interface NodeModuleInternal {
  _load: (request: string, parent: NodeModule | undefined, isMain: boolean) => unknown;
}

const nodeModule = Module as unknown as NodeModuleInternal;

function buildApiFunction(): string {
  const result = spawnSync(process.execPath, [BUILD_SCRIPT], {
    cwd: ROOT,
    encoding: 'utf8'
  });
  if (result.status !== 0) {
    throw new Error(result.stderr || result.stdout || 'build:api failed');
  }
  return ARTIFACT;
}
const VALID_DESCRIPTION =
  'A bicycle helmet equipped with an accelerometer and gyroscope that detects collisions and sends an emergency notification with GPS coordinates through a connected smartphone.';

type Handler = (
  req: { method?: string; headers: Record<string, string | undefined>; body?: unknown },
  res: { status: (code: number) => HandlerResponse; json: (body: unknown) => void }
) => Promise<void>;

interface HandlerResponse {
  status: (code: number) => HandlerResponse;
  json: (body: unknown) => void;
}

function loadHandler(): Handler {
  const require = createRequire(pathToFileURL(ARTIFACT).href);
  delete require.cache[require.resolve(ARTIFACT)];
  const mod = require(ARTIFACT) as Handler | { default?: Handler };
  const handler = typeof mod === 'function' ? mod : mod.default;
  if (typeof handler !== 'function') {
    throw new Error('API artifact did not export a function handler');
  }
  return handler;
}

async function invoke(
  handler: Handler,
  req: { method?: string; headers?: Record<string, string | undefined>; body?: unknown }
) {
  const calls: Array<['status' | 'json', unknown]> = [];
  const res: HandlerResponse = {
    status(code) {
      calls.push(['status', code]);
      return res;
    },
    json(body) {
      calls.push(['json', body]);
    }
  };
  await handler(
    { method: req.method, headers: req.headers ?? {}, body: req.body },
    res
  );
  const status = calls.find((call) => call[0] === 'status')?.[1];
  const body = calls.find((call) => call[0] === 'json')?.[1];
  return { status, body, calls };
}

const originalLoad = nodeModule._load;
let openaiLoads = 0;

function installOpenAIMock(features: Array<{ label: string; detail: string; sourcePhrase: string }>) {
  openaiLoads = 0;
  class OpenAI {
    beta = {
      chat: {
        completions: {
          parse: async () => ({
            choices: [{ message: { parsed: { features } } }]
          })
        }
      }
    };
  }
  nodeModule._load = function patched(request, parent, isMain) {
    if (request === 'openai') {
      openaiLoads += 1;
      return OpenAI;
    }
    if (request.startsWith('openai/')) {
      openaiLoads += 1;
      return { zodResponseFormat: () => ({ type: 'json_schema' }) };
    }
    return originalLoad(request, parent, isMain);
  };
}

afterEach(() => {
  nodeModule._load = originalLoad;
  delete process.env.LIVE_EXTRACTION_ENABLED;
  delete process.env.OPENAI_API_KEY;
  delete process.env.OPENAI_MODEL;
});

describe('CJS extract-features artifact', () => {
  it('is a loadable CommonJS function with no unresolved local imports or secrets', async () => {
    const outfile = await buildApiFunction();
    expect(outfile).toBe(ARTIFACT);

    const source = readFileSync(ARTIFACT, 'utf8');
    expect(source.startsWith('/* Generated by scripts/build-api.mjs.')).toBe(true);
    expect(source).toContain('module.exports');
    expect(source).not.toMatch(/^(export |import )/m);
    expect(source).not.toMatch(/(?:require|import)\(["']\.\.?\/[^"']+\.(?:ts|js)["']\)/);
    expect(source).toContain('require("openai")');
    expect(source).not.toMatch(/sk-(?:live|proj|test)-[A-Za-z0-9]+/);
    expect(source).not.toContain('OPENAI_API_KEY=');

    const handler = loadHandler();
    expect(typeof handler).toBe('function');
    expect(existsSync(path.join(ROOT, 'api/extract-features.ts'))).toBe(false);
    const vercelConfig = JSON.parse(readFileSync(path.join(ROOT, 'vercel.json'), 'utf8')) as {
      functions: Record<string, unknown>;
    };
    expect(Object.keys(vercelConfig.functions).sort()).toEqual([
      'api/extract-features.js',
      'api/search-patents.js'
    ]);
    expect(vercelConfig.functions['api/extract-features.js']).not.toHaveProperty('includeFiles');
    expect(vercelConfig.functions['api/search-patents.js']).not.toHaveProperty('includeFiles');
  });

  it('returns METHOD_NOT_ALLOWED for GET without loading OpenAI', async () => {
    await buildApiFunction();
    installOpenAIMock([]);
    const handler = loadHandler();
    const result = await invoke(handler, { method: 'GET', headers: {} });
    expect(result.status).toBe(405);
    expect(result.body).toMatchObject({ error: { code: 'METHOD_NOT_ALLOWED' } });
    expect(openaiLoads).toBe(0);
  });

  it('returns SERVICE_UNAVAILABLE for a valid POST when the gate is off, without loading OpenAI', async () => {
    await buildApiFunction();
    installOpenAIMock([]);
    const handler = loadHandler();
    const result = await invoke(handler, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: { description: VALID_DESCRIPTION }
    });
    expect(result.status).toBe(503);
    expect(result.body).toMatchObject({ error: { code: 'SERVICE_UNAVAILABLE' } });
    expect(openaiLoads).toBe(0);
  });

  it('loads a mocked OpenAI adapter after the gate and normalizes source phrases', async () => {
    await buildApiFunction();
    installOpenAIMock([
      {
        label: 'Protective bicycle helmet',
        detail: 'A helmet form factor for cycling.',
        sourcePhrase: 'A bicycle helmet'
      },
      {
        label: 'Inertial collision sensing',
        detail: 'Collision detection from accelerometer and gyroscope signals.',
        sourcePhrase: 'an accelerometer and gyroscope that detects collisions'
      }
    ]);
    process.env.LIVE_EXTRACTION_ENABLED = 'true';
    process.env.OPENAI_API_KEY = 'sk-test-not-a-real-key';

    const handler = loadHandler();
    const result = await invoke(handler, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: { description: VALID_DESCRIPTION }
    });

    expect(result.status).toBe(200);
    expect(result.body).toMatchObject({
      mode: 'live',
      features: [
        { id: 'F01', sourcePhrase: 'A bicycle helmet' },
        { id: 'F02', sourcePhrase: 'an accelerometer and gyroscope that detects collisions' }
      ]
    });
    expect(openaiLoads).toBeGreaterThan(0);
  });
});
