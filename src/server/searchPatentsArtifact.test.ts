import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { describe, expect, it } from 'vitest';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ARTIFACT = path.join(ROOT, 'api/search-patents.js');
const BUILD_SCRIPT = path.join(ROOT, 'scripts/build-api.mjs');

function buildApi(): void {
  const result = spawnSync(process.execPath, [BUILD_SCRIPT], { cwd: ROOT, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || 'build:api failed');
}

describe('search-patents serverless artifact', () => {
  it('is a CommonJS Vercel entrypoint and does not embed credentials', () => {
    buildApi();
    const source = readFileSync(ARTIFACT, 'utf8');
    expect(source.startsWith('/* Generated by scripts/build-api.mjs')).toBe(true);
    expect(source.includes('module.exports')).toBe(true);
    expect(source.includes('\nimport ')).toBe(false);
    expect(source.includes('EPO_CONSUMER_KEY')).toBe(true);
    expect(source).not.toMatch(/sk-(?:live|proj|test)-[A-Za-z0-9]+/);
    expect(source).not.toContain('EPO_CONSUMER_KEY=');
    expect(source).not.toContain('EPO_CONSUMER_SECRET=');
    const require = createRequire(pathToFileURL(ARTIFACT).href);
    delete require.cache[require.resolve(ARTIFACT)];
    const loaded = require(ARTIFACT) as { default?: unknown };
    const handler = typeof loaded === 'function' ? loaded : loaded.default;
    expect(typeof handler).toBe('function');
  });
});
