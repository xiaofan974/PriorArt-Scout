import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apiPackagePath = path.join(root, 'api/package.json');

const FUNCTIONS = [
  {
    entry: path.join(root, 'src/server/extractFeaturesEntry.ts'),
    outfile: path.join(root, 'api/extract-features.js')
  },
  {
    entry: path.join(root, 'src/server/searchPatentsEntry.ts'),
    outfile: path.join(root, 'api/search-patents.js')
  }
];

const BANNER = '/* Generated by scripts/build-api.mjs. Do not edit. */\n';

async function bundleFunction(entry, outfile) {
  await mkdir(path.dirname(outfile), { recursive: true });
  await esbuild.build({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    legalComments: 'none',
    sourcemap: false,
    logLevel: 'silent',
    // Keep the OpenAI SDK out of the esbuild graph. CJS require() loads it from
    // node_modules after the production feature gate, which avoids the ESM
    // node-fetch/stream crash and leaves the package mockable in tests.
    external: ['openai', 'openai/*']
  });

  const generated = await readFile(outfile, 'utf8');
  if (generated.startsWith('import ') || generated.includes('\nimport ')) {
    throw new Error(`${outfile} is ESM; Vercel api/*.js with root type:module cannot load it as CommonJS.`);
  }
  if (!generated.includes('require(') && !generated.includes('module.exports')) {
    throw new Error(`${outfile} is missing CommonJS exports.`);
  }
  if (/(?:require|import)\(["']\.\.?\/[^"']+\.(?:ts|js)["']\)/.test(generated)) {
    throw new Error(`${outfile} still contains unresolved local .js/.ts imports.`);
  }
  await writeFile(outfile, BANNER + generated);
  return outfile;
}

export async function buildApiFunction() {
  const apiPackage = JSON.parse(await readFile(apiPackagePath, 'utf8'));
  if (apiPackage.type !== 'commonjs') {
    throw new Error(
      'api/package.json must set "type": "commonjs" so Vercel deploys api/*.js functions as CommonJS.'
    );
  }
  const written = [];
  for (const fn of FUNCTIONS) {
    written.push(await bundleFunction(fn.entry, fn.outfile));
  }
  return written[0];
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const apiPackage = JSON.parse(await readFile(apiPackagePath, 'utf8'));
  if (apiPackage.type !== 'commonjs') {
    throw new Error('api/package.json must set "type": "commonjs".');
  }
  for (const fn of FUNCTIONS) {
    await bundleFunction(fn.entry, fn.outfile);
    console.log('Wrote', path.relative(root, fn.outfile));
  }
}
