import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'src/server/extractFeaturesEntry.ts');
const outfile = path.join(root, 'api/extract-features.js');
const apiPackagePath = path.join(root, 'api/package.json');

const BANNER = '/* Generated by scripts/build-api.mjs. Do not edit. */\n';

export async function buildApiFunction() {
  const apiPackage = JSON.parse(await readFile(apiPackagePath, 'utf8'));
  if (apiPackage.type !== 'commonjs') {
    throw new Error(
      'api/package.json must set "type": "commonjs" so Vercel deploys api/extract-features.js as CommonJS.'
    );
  }

  await mkdir(path.dirname(outfile), { recursive: true });
  await esbuild.build({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    legalComments: 'none',
    sourcemap: false,
    logLevel: 'silent',
    // Keep the OpenAI SDK out of the esbuild graph. CJS require() loads it from
    // node_modules after the production feature gate, which avoids the ESM
    // node-fetch/stream crash and leaves the package mockable in tests.
    external: ['openai', 'openai/*']
  });

  const generated = await readFile(outfile, 'utf8');
  if (generated.startsWith('import ') || generated.includes('\nimport ')) {
    throw new Error('API bundle is ESM; Vercel api/*.js with root type:module cannot load it as CommonJS.');
  }
  if (!generated.includes('require(') && !generated.includes('module.exports')) {
    throw new Error('API bundle is missing CommonJS exports.');
  }
  if (/(?:require|import)\(["']\.\.?\/[^"']+\.(?:ts|js)["']\)/.test(generated)) {
    throw new Error('API bundle still contains unresolved local .js/.ts imports.');
  }

  await writeFile(outfile, BANNER + generated);
  return outfile;
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  await buildApiFunction();
  console.log('Wrote', path.relative(root, outfile));
}
